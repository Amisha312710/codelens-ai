    def test_context_validation_and_citation_extraction(self):
        """7. Tests context validation rules and citation extraction."""
        # Test validate_context: drops duplicate spans and empty sources
        raw_items = [
            {"file_path": "a.py", "start_line": 1, "end_line": 10, "source_code": "def foo(): pass"},
            {"file_path": "a.py", "start_line": 1, "end_line": 10, "source_code": "def foo(): pass"},  # duplicate
            {"file_path": "b.py", "start_line": 5, "end_line": 15, "source_code": "   "},             # empty code
            {"file_path": "c.py", "start_line": None, "end_line": 10, "source_code": "x = 1"},         # missing line
            {"file_path": "d.py", "start_line": 1, "end_line": 5, "source_code": "def bar(): pass"},
        ]
        validated = validate_context(raw_items)
        self.assertEqual(len(validated), 2)
        self.assertEqual(validated[0]["file_path"], "a.py")
        self.assertEqual(validated[1]["file_path"], "d.py")

        # Test extract_citations: extracts predictable citations only
        sample_answer = (
            "The core is in [Source: sample/core.py:10-20]. "
            "Helper in [Source: sample/helpers.py:1-5]. "
            "Repeated [Source: sample/core.py:10-20]."
        )
        parsed = extract_citations(sample_answer)
        self.assertEqual(parsed, ["sample/core.py:10-20", "sample/helpers.py:1-5"])

