    def test_empty_retrieval_insufficient_evidence(self):
        """4. Empty retrieval results return early with insufficient evidence without calling LLM."""
        mock_provider = MockLLMProvider()

        # Temporarily mock search_repository to return empty results
        original_search = self.search_service.search_repository
        try:
            self.search_service.search_repository = lambda repo_url, query, top_k: {
                "repository_url": repo_url,
                "query": query,
                "results": [],
            }

            res = self.search_service.ask_repository(
                repo_url=self.repo_url,
                question="How does unknown_function work?",
                top_k=5,
                provider=mock_provider,
            )

            # LLM provider must NOT be called when evidence is empty
            self.assertEqual(mock_provider.call_count, 0)
            self.assertEqual(res["citations"], [])
            self.assertEqual(res["evidence_used"], [])
            self.assertIn("couldn't find enough evidence", res["answer"].lower())
        finally:
            self.search_service.search_repository = original_search

    def test_missing_api_key(self):
        """5. Missing API key raises server configuration error (HTTPException 500)."""
        old_groq = os.environ.pop("GROQ_API_KEY", None)
        old_openai = os.environ.pop("OPENAI_API_KEY", None)
        old_settings_groq = settings.GROQ_API_KEY
        old_settings_openai = settings.OPENAI_API_KEY
        settings.GROQ_API_KEY = None
        settings.OPENAI_API_KEY = None
