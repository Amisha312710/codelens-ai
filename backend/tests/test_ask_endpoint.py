            settings.GROQ_API_KEY = old_settings_groq
            settings.OPENAI_API_KEY = old_settings_openai
            if old_groq is not None:
                os.environ["GROQ_API_KEY"] = old_groq
            if old_openai is not None:
                os.environ["OPENAI_API_KEY"] = old_openai

