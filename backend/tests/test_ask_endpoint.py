class MockLLMProvider(LLMProvider):
    """
    Deterministic mock provider for offline testing without calling live OpenAI APIs.
    """

    def __init__(self, answer_template: Optional[str] = None, fail: bool = False):
        self.answer_template = answer_template
        self.fail = fail
        self.call_count = 0
        self.last_prompt = None
        self.last_system_prompt = None

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        self.call_count += 1
        self.last_prompt = prompt
        self.last_system_prompt = system_prompt

        if self.fail:
            raise ConnectionError("Simulated LLM API network error")

        if self.answer_template is not None:
            return self.answer_template

        # Grounded answer with predictable citations
        return (
            "The answer is generated by get_answer() in helpers [Source: sample/helpers.py:1-3]. "
            "In addition, hmm() in the core module invokes get_answer [Source: sample/core.py:13-25]."
        )


class TestAskEndpoint(unittest.TestCase):
    def setUp(self):
        self.search_service = SearchService()
        self.repo_url = "https://github.com/kennethreitz/samplemod"

    def test_valid_grounded_question(self):
        """1. Valid grounded question returns answer, parsed citations, and validated evidence."""
        mock_provider = MockLLMProvider()
        res = self.search_service.ask_repository(
            repo_url=self.repo_url,
            question="Where is the answer generated?",
            top_k=5,
            provider=mock_provider,
        )

        # Provider invoked once with evidence
        self.assertEqual(mock_provider.call_count, 1)
        self.assertIn("Question: Where is the answer generated?", mock_provider.last_prompt)
        self.assertIn("Evidence 1", mock_provider.last_prompt)
        self.assertIn("sample/helpers.py", mock_provider.last_prompt)

        # Structured response fields
        self.assertEqual(res["question"], "Where is the answer generated?")
        self.assertIn("get_answer()", res["answer"])
        self.assertIsInstance(res["citations"], list)
        self.assertIn("sample/helpers.py:1-3", res["citations"])
        self.assertIn("sample/core.py:13-25", res["citations"])
        self.assertTrue(len(res["evidence_used"]) > 0)

        # Verify evidence metadata structure
        top_ev = res["evidence_used"][0]
        self.assertIn("file_path", top_ev)
        self.assertIn("symbol_name", top_ev)
        self.assertIn("source_code", top_ev)
        self.assertIn("start_line", top_ev)
        self.assertIn("end_line", top_ev)
        self.assertIn("retrieval_sources", top_ev)

